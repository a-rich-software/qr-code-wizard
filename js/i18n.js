function readSavedLang() {
  try {
    var saved = localStorage.getItem(LANG_KEY);
    if (saved === "he" || saved === "en") {
      return saved;
    }
    var legacy = localStorage.getItem(LEGACY_LANG_KEY);
    if (legacy === "he" || legacy === "en") {
      localStorage.setItem(LANG_KEY, legacy);
      localStorage.removeItem(LEGACY_LANG_KEY);
      return legacy;
    }
  } catch (err) {}
  return "";
}

function detectInterfaceLang() {
  var saved = readSavedLang();
  if (saved === "he" || saved === "en") {
    return saved;
  }
  var list = [];
  if (navigator.languages && navigator.languages.length) {
    list = list.concat(navigator.languages);
  }
  if (navigator.language) {
    list.push(navigator.language);
  }
  if (navigator.userLanguage) {
    list.push(navigator.userLanguage);
  }
  var i;
  var tag;
  for (i = 0; i < list.length; i += 1) {
    tag = String(list[i] || "").toLowerCase();
    if (tag === "he" || tag.indexOf("he-") === 0 || tag === "iw" || tag.indexOf("iw-") === 0) {
      return "he";
    }
  }
  return "en";
}

function t(key, vars) {
  var lang = document.documentElement.getAttribute("data-lang") || (document.documentElement.lang === "he" ? "he" : "en");
  var table = I18N[lang] || I18N.en;
  var value = table[key] || I18N.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach(function (name) {
      value = value.replace(new RegExp("\\{" + name + "\\}", "g"), vars[name]);
    });
  }
  return value;
}

function applyStaticI18n() {
  document.querySelectorAll("[data-i18n]").forEach(function (node) {
    node.textContent = t(node.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (node) {
    node.setAttribute("placeholder", t(node.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(function (node) {
    node.setAttribute("aria-label", t(node.getAttribute("data-i18n-aria")));
  });
  var pageTitleKey = document.body && document.body.getAttribute("data-title-key");
  var pageDescKey = document.body && document.body.getAttribute("data-desc-key");
  document.title = t(pageTitleKey || "title");
  var descText = t(pageDescKey || "description");
  var desc = document.querySelector('meta[name="description"]');
  if (desc) {
    desc.setAttribute("content", descText);
  }
  var ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) {
    ogTitle.setAttribute("content", t(pageTitleKey || "title"));
  }
  var ogDesc = document.querySelector('meta[property="og:description"]');
  if (ogDesc) {
    ogDesc.setAttribute("content", descText);
  }
  var ogLocale = document.querySelector('meta[property="og:locale"]');
  if (ogLocale) {
    ogLocale.setAttribute("content", (document.documentElement.getAttribute("data-lang") || "en") === "he" ? "he_IL" : "en_US");
  }
  var twitterTitle = document.querySelector('meta[name="twitter:title"]');
  if (twitterTitle) {
    twitterTitle.setAttribute("content", t(pageTitleKey || "title"));
  }
  var twitterDesc = document.querySelector('meta[name="twitter:description"]');
  if (twitterDesc) {
    twitterDesc.setAttribute("content", descText);
  }
  var itemName = document.querySelector('meta[itemprop="name"]');
  if (itemName) {
    itemName.setAttribute("content", t(pageTitleKey || "title"));
  }
  var itemDesc = document.querySelector('meta[itemprop="description"]');
  if (itemDesc) {
    itemDesc.setAttribute("content", descText);
  }
}

function setDocumentLang(lang, persistChoice) {
  var next = lang === "he" ? "he" : "en";
  document.documentElement.lang = next;
  document.documentElement.dir = next === "he" ? "rtl" : "ltr";
  document.documentElement.setAttribute("data-lang", next);
  if (persistChoice) {
    try {
      localStorage.setItem(LANG_KEY, next);
    } catch (err) {}
  }
  applyStaticI18n();
  document.querySelectorAll("[data-lang-block]").forEach(function (node) {
    node.hidden = node.getAttribute("data-lang-block") !== next;
  });
  document.querySelectorAll("[data-lang-set]").forEach(function (btn) {
    var on = btn.getAttribute("data-lang-set") === next;
    btn.classList.toggle("is-on", on);
    btn.setAttribute("aria-pressed", on ? "true" : "false");
  });
}
